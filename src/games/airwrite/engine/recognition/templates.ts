/**
 * Shape library for the on-device recognizer.
 * Each character has one or more variants; each variant is a list of strokes
 * in a 0-100 box (y grows downward). Stroke order and direction don't matter
 * to $P, so only the shape needs to be right.
 */
import type { StrokeXY, XY } from "./pdollar";

type Variant = StrokeXY[];

const L = (...pts: XY[]): StrokeXY => pts;

/** Elliptical arc; angles in degrees, 0 = right, 90 = down (screen space). */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, steps = 18): StrokeXY {
  const out: StrokeXY = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180;
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
}

/** Concatenate path pieces into one continuous stroke. */
const join = (...parts: StrokeXY[]): StrokeXY => parts.flat();

